"""Markdown data docs, one page per contract and an index."""

from __future__ import annotations

from collections.abc import Iterable

from dctl.generators.ddl import sql_type
from dctl.generators.expectations import build
from dctl.model import Column, Contract
from dctl.target import Target


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _checks(column: Column) -> str:
    c = column.checks
    parts = []
    if c.min is not None:
        parts.append(f"min {c.min:g}")
    if c.max is not None:
        parts.append(f"max {c.max:g}")
    if c.pattern:
        parts.append(f"pattern `{c.pattern}`")
    if c.allowed_values:
        parts.append("one of " + ", ".join(f"`{v}`" for v in c.allowed_values))
    return _cell("; ".join(parts)) if parts else ""


def render(contract: Contract, target: Target) -> str:
    keys = set(contract.primary_key)
    lines = [
        f"# {contract.schema}.{contract.table}",
        "",
        "<!-- Generated by dctl from the contract. Do not edit by hand. -->",
        "",
        contract.description,
        "",
        "| Property | Value |",
        "| --- | --- |",
        f"| Contract | `contracts/{contract.id}.yaml`, version {contract.version}, {contract.status} |",
        f"| Unity Catalog name | `{target.full_name(contract)}` |",
        f"| Storage location | `{target.location(contract)}` |",
        f"| Owner | {contract.owner_team} (`{contract.owner_group}`) |",
        f"| Steward | `{contract.steward_group}` |",
        f"| Primary key | {', '.join(f'`{k}`' for k in contract.primary_key)} |",
        f"| Clustered by | {', '.join(f'`{k}`' for k in contract.cluster_by) or 'none'} |",
        f"| Highest classification | {contract.max_classification} |",
        f"| Contains personal data | {'yes' if contract.contains_pii else 'no'} |",
        f"| Fabric exposure | {contract.exposure} |",
        "",
        "## Service levels",
        "",
        "| Commitment | Value |",
        "| --- | --- |",
        f"| Freshness | `{contract.freshness_column}` no older than {contract.max_delay_hours:g} hours |",
        f"| Update frequency | {contract.update_frequency} |",
    ]
    if contract.availability_percent is not None:
        lines.append(f"| Availability | {contract.availability_percent:g} percent |")
    if contract.retention_days is not None:
        lines.append(f"| Retention | {contract.retention_days} days |")
    lines += [
        "",
        "## Columns",
        "",
        "| Column | Type | Required | Classification | Checks | Description |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for column in contract.columns:
        name = f"`{column.name}`" + (" (key)" if column.name in keys else "")
        classification = column.classification + (", pii" if column.pii else "")
        required = "no" if column.nullable else "yes"
        lines.append(
            f"| {name} | `{sql_type(column.type)}` | {required} | {classification} | {_checks(column)} "
            f"| {_cell(column.description)} |"
        )
    lines += ["", "## Data quality", "", "| Expectation | On violation | Predicate |", "| --- | --- | --- |"]
    for e in build(contract):
        lines.append(f"| `{e.name}` | {e.action} | `{_cell(e.predicate)}` |")
    if contract.measures:
        lines += ["", "## Semantic model measures", "", "| Measure | Format | DAX |", "| --- | --- | --- |"]
        for m in contract.measures:
            lines.append(f"| {m.name} | `{m.format or ''}` | `{_cell(m.expression)}` |")
    lines.append("")
    return "\n".join(lines)


def render_index(contracts: Iterable[Contract], target: Target) -> str:
    lines = [
        "# Gold data products",
        "",
        "<!-- Generated by dctl from the contracts. Do not edit by hand. -->",
        "",
        f"Catalog `{target.catalog}`. Each page is rendered from the contract of the same name.",
        "",
        "| Table | Version | Owner | Freshness | Classification | Fabric |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for c in contracts:
        lines.append(
            f"| [{c.schema}.{c.table}]({c.id}.md) | {c.version} | {c.owner_team} | {c.max_delay_hours:g} h "
            f"| {c.max_classification} | {c.exposure} |"
        )
    lines.append("")
    return "\n".join(lines)
