"""Lakeflow Declarative Pipelines expectations, grouped by the action taken on a violation."""

from __future__ import annotations

from dataclasses import dataclass

from dctl.model import Column, Contract


@dataclass(frozen=True)
class Expectation:
    name: str
    predicate: str
    action: str  # warn, drop or fail


def _sql_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _number(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else repr(value)


def column_predicates(column: Column) -> list[tuple[str, str]]:
    """Value checks for one column as (suffix, predicate). Nullable columns accept NULL."""
    checks = column.checks
    out: list[tuple[str, str]] = []
    if checks.min is not None and checks.max is not None:
        out.append(("in_range", f"{column.name} BETWEEN {_number(checks.min)} AND {_number(checks.max)}"))
    elif checks.min is not None:
        out.append(("min", f"{column.name} >= {_number(checks.min)}"))
    elif checks.max is not None:
        out.append(("max", f"{column.name} <= {_number(checks.max)}"))
    if checks.pattern:
        out.append(("pattern", f"{column.name} RLIKE {_sql_string(checks.pattern)}"))
    if checks.allowed_values:
        values = ", ".join(_sql_string(v) for v in checks.allowed_values)
        out.append(("allowed", f"{column.name} IN ({values})"))
    if column.nullable:
        out = [(suffix, f"{column.name} IS NULL OR {pred}") for suffix, pred in out]
    return out


def build(contract: Contract) -> list[Expectation]:
    """Primary key columns fail the update, other column checks drop the row, table rules keep their action."""
    keys = set(contract.primary_key)
    result: list[Expectation] = []
    for column in contract.columns:
        if not column.nullable:
            action = "fail" if column.name in keys else "drop"
            result.append(Expectation(f"{column.name}_not_null", f"{column.name} IS NOT NULL", action))
        result += [Expectation(f"{column.name}_{suffix}", pred, "drop") for suffix, pred in column_predicates(column)]
    result += [Expectation(rule.name, rule.expression, rule.on_violation) for rule in contract.quality]
    return result


def _dict_literal(name: str, items: list[Expectation]) -> list[str]:
    if not items:
        return [f"{name}: dict[str, str] = {{}}"]
    lines = [f"{name}: dict[str, str] = {{"]
    lines += [f"    {e.name!r}: {e.predicate!r}," for e in items]
    lines.append("}")
    return lines


def render(contract: Contract) -> str:
    items = build(contract)
    lines = [
        f'"""Expectations for {contract.schema}.{contract.table}, contract version {contract.version}.',
        "",
        f"Generated by dctl from contracts/{contract.id}.yaml. Do not edit by hand.",
        "Use with dp.expect_all_or_fail, dp.expect_all_or_drop and dp.expect_all.",
        '"""',
        "",
        f"CONTRACT_ID = {contract.id!r}",
        f"CONTRACT_VERSION = {contract.version!r}",
        "",
    ]
    for name, action in (("EXPECT_OR_FAIL", "fail"), ("EXPECT_OR_DROP", "drop"), ("EXPECT", "warn")):
        lines += _dict_literal(name, [e for e in items if e.action == action])
        lines.append("")
    return "\n".join(lines)
