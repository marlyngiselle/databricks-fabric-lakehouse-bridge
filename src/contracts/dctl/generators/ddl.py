"""Delta DDL for Unity Catalog: columns with comments, informational keys, CHECK constraints and tags."""

from __future__ import annotations

import re

from dctl.generators.expectations import build
from dctl.model import Contract, DataType
from dctl.target import Target

# Delta rejects CHECK constraints that are not deterministic. Those rules stay in the pipeline only.
_NON_DETERMINISTIC = re.compile(r"\b(current_timestamp|current_date|now|rand|randn|uuid)\s*\(", re.IGNORECASE)


def is_deterministic(predicate: str) -> bool:
    return _NON_DETERMINISTIC.search(predicate) is None


def sql_type(data_type: DataType) -> str:
    return {
        "string": "STRING",
        "int": "INT",
        "bigint": "BIGINT",
        "double": "DOUBLE",
        "boolean": "BOOLEAN",
        "date": "DATE",
        "timestamp": "TIMESTAMP",
    }.get(data_type.name, str(data_type).upper())


def _literal(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _tags(pairs: list[tuple[str, str]]) -> str:
    return ", ".join(f"{_literal(k)} = {_literal(v)}" for k, v in pairs)


def render(contract: Contract, target: Target) -> str:
    name = target.full_name(contract)
    width = max(len(c.name) for c in contract.columns)
    lines = [
        f"-- {name}, contract version {contract.version}.",
        f"-- Generated by dctl from contracts/{contract.id}.yaml. Do not edit by hand.",
        "",
        f"CREATE TABLE IF NOT EXISTS {name} (",
    ]
    body = []
    for column in contract.columns:
        not_null = "" if column.nullable else " NOT NULL"
        body.append(
            f"  {column.name.ljust(width)} {sql_type(column.type)}{not_null} COMMENT {_literal(column.description)}"
        )
    body.append(f"  CONSTRAINT {contract.table}_pk PRIMARY KEY ({', '.join(contract.primary_key)}) NOT ENFORCED")
    lines.append(",\n".join(body))
    lines.append(")")
    lines.append("USING DELTA")
    if contract.cluster_by:
        lines.append(f"CLUSTER BY ({', '.join(contract.cluster_by)})")
    lines.append(f"LOCATION {_literal(target.location(contract))}")
    lines.append(f"COMMENT {_literal(contract.description)}")
    props = [
        ("delta.enableChangeDataFeed", "true"),
        ("contract.id", contract.id),
        ("contract.version", contract.version),
    ]
    lines.append("TBLPROPERTIES (")
    lines.append(",\n".join(f"  {_literal(k)} = {_literal(v)}" for k, v in props))
    lines.append(");")
    lines.append("")

    lines.append(f"ALTER TABLE {name} OWNER TO `{contract.owner_group}`;")
    table_tags = [
        ("domain", contract.domain),
        ("owner_team", contract.owner_team),
        ("steward", contract.steward_group),
        ("classification", contract.max_classification),
        ("contains_pii", str(contract.contains_pii).lower()),
        ("freshness_sla_hours", f"{contract.max_delay_hours:g}"),
        ("fabric_exposure", contract.exposure),
    ]
    lines.append(f"ALTER TABLE {name} SET TAGS ({_tags(table_tags)});")
    for column in contract.columns:
        tags = [("classification", column.classification)]
        if column.pii:
            tags.append(("pii", "true"))
        lines.append(f"ALTER TABLE {name} ALTER COLUMN {column.name} SET TAGS ({_tags(tags)});")
    lines.append("")

    # Delta CHECK constraints are the last line of defence behind the pipeline expectations.
    # Warn rules stay out on purpose: a constraint would turn a warning into a failed write.
    checks = [
        e
        for e in build(contract)
        if e.action != "warn" and not e.name.endswith("_not_null") and is_deterministic(e.predicate)
    ]
    for expectation in checks:
        lines.append(f"ALTER TABLE {name} DROP CONSTRAINT IF EXISTS {expectation.name};")
        lines.append(f"ALTER TABLE {name} ADD CONSTRAINT {expectation.name} CHECK ({expectation.predicate});")
    lines.append("")
    return "\n".join(lines)
